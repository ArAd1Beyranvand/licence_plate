  /// The prefecture of [letters] (one to three), or null when they match no
  /// code or several.
  static String? lookup(String letters) {
    if (letters.isEmpty) return null;
    final String code = letters.length > 2 ? letters.substring(0, 2) : letters;
    final Set<String> names = <String>{
      for (final MapEntry<String, String> e in _prefectures.entries)
        if (e.key.startsWith(code)) e.value,
    };
    return names.length == 1 ? names.single : null;
  }

  static String? captionOf(String Function(String key) group) =>
      lookup(group('letters'));
}
