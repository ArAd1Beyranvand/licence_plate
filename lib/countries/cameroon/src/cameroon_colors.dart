import 'package:flutter/widgets.dart';

/// Each colour is the modal pixel of the flattened photo over the region it
/// fills (`____1` regular, `Kameroen3_license_plate` diplomatic). The
/// diplomatic green is the median of the photo's green pixels.
abstract final class CameroonColors {
  static const Color orange = Color(0xFFFB6800);
  static const Color black = Color(0xFF000000);

  static const Color diplomaticGreen = Color(0xFF01FEB1);
  static const Color white = Color(0xFFFFFFFF);

  static const Color sticker = Color(0xFF808080);
}
